function buildImportance(node) {
  if (node.keyIdea && !tooSimilar(node.keyIdea, node.detail)) {
    return node.keyIdea
  }

  return ''
}

function buildRole(node, context) {
  const incoming = primaryConnection(context.incoming)
  const outgoing = primaryConnection(context.outgoing)

  const parts = []
  const before = incomingRole(incoming)
  const after = outgoingRole(outgoing)

  if (before) parts.push(before)
  if (after) parts.push(after)

  if (!parts.length) {
    return ''
  }

  return parts.join(' ')
}

function buildQuestion(node) {
  if (node.question && !isGenericQuestion(node.question)) {
    return node.question
  }

  const variantsByCategory = {
    claim: [
      `¿Qué afirma «${node.title}» y qué problema permite entender mejor?`,
      `¿Qué compromiso introduce «${node.title}» dentro de esta fase?`,
    ],
    problem: [
      `¿Qué dificultad hace visible «${node.title}»?`,
      `¿Por qué «${node.title}» cuenta como un problema para el modo de proceder examinado?`,
    ],
    method: [
      `¿Qué cambia en el modo de proceder cuando aparece «${node.title}»?`,
      `¿Qué regla de investigación hace visible «${node.title}»?`,
    ],
    evidence: [
      `¿Qué muestra el ejemplo «${node.title}» y qué sería un error concluir de él?`,
      `¿Qué aspecto del argumento vuelve concreto «${node.title}»?`,
    ],
    contrast: [
      `¿Qué confusión evita la distinción introducida en «${node.title}»?`,
      `¿Qué dos alcances o puntos de vista obliga a separar «${node.title}»?`,
    ],
    conclusion: [
      `¿Qué resultado queda establecido al llegar a «${node.title}»?`,
      `¿Qué se ha ganado en el argumento al llegar a «${node.title}»?`,
    ],
    practical: [
      `¿Qué queda abierto en «${node.title}» sin convertirlo en conocimiento especulativo?`,
      `¿Por qué «${node.title}» exige distinguir uso teórico y uso práctico de la razón?`,
    ],
    tradition: [
      `¿Qué cambio de método representa «${node.title}» dentro de la reconstrucción de Kant?`,
      `¿Por qué Kant introduce «${node.title}» en este punto del argumento?`,
    ],
  }

  return stableVariant(
    node.id,
    variantsByCategory[node.category] || variantsByCategory.claim,
  )
}

function buildAnswer(node, importance) {
  if (
    node.answer &&
    !tooSimilar(node.answer, node.detail) &&
    !tooSimilar(node.answer, importance)
  ) {
    return node.answer
  }

  if (
    node.detail &&
    (!importance || !tooSimilar(node.detail, importance))
  ) {
    return node.detail
  }

  return importance || node.detail || node.answer || ''
}

function buildFullCuration(graph, node) {
  const context = graphContext(graph, node)
  const readingCue = specificReadingCue(node)
  const keyIdea = buildImportance(node)
  const explanation = buildRole(node, context)
  const question = buildQuestion(node)
  const answer = buildAnswer(node, keyIdea)

  return {
    readingCue,
    keyIdea,
    explanation,
    question,
    answer,
  }
}

export function buildKantDetailedGuideSteps(graph) {
  const orderedNodes = (graph.guideNodeIds || graph.nodes.map((node) => node.id))
    .map((nodeId) => graph.nodes.find((node) => node.id === nodeId))
    .filter(Boolean)

  return orderedNodes.map((node) => {
    const editorial =
      CURATED_GUIDE[node.id] ||
      CURATED_BY_PHASE_TITLE[`${graph.id}::${node.title}`] ||
      {}
    const generated = buildFullCuration(graph, node)

    const readingCue = editorial.readingCue || generated.readingCue
    const keyIdea = editorial.keyIdea || generated.keyIdea
    const explanation = editorial.explanation || generated.explanation
    const question = editorial.question || generated.question
    const answer = editorial.answer || generated.answer

    const showKeyIdea =
      Boolean(keyIdea) &&
      !tooSimilar(keyIdea, node.detail)

    const showExplanation =
      Boolean(explanation) &&
      !tooSimilar(explanation, node.detail) &&
      !tooSimilar(explanation, keyIdea)

    return {
      nodeId: node.id,
      title: node.title,
      readingCue,
      explanation: showExplanation ? explanation : '',
      keyIdea,
      question,
      answer,
      isCurated: true,
      showKeyIdea,
      source: Object.keys(editorial).length ? 'manual' : 'contextual',
    }
  })
}

