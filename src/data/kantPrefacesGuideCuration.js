function stableVariant(value, variants) {
  let score = 0
  for (const char of String(value || '')) {
    score = (score * 31 + char.charCodeAt(0)) >>> 0
  }
  return variants[score % variants.length]
}

function titleIncludes(node, ...needles) {
  const title = normalizeText(node.title)
  const words = new Set(title.split(' ').filter(Boolean))

  return needles.some((needle) => {
    const normalized = normalizeText(needle)
    if (!normalized) return false
    return normalized.includes(' ')
      ? title.includes(normalized)
      : words.has(normalized)
  })
}

function nodeById(graph, nodeId) {
  return graph.nodes.find((candidate) => candidate.id === nodeId) || null
}

function graphContext(graph, node) {
  const incoming = (graph.edges || [])
    .filter((edge) => edge.target === node.id)
    .map((edge) => ({ edge, node: nodeById(graph, edge.source) }))
    .filter((item) => item.node)

  const outgoing = (graph.edges || [])
    .filter((edge) => edge.source === node.id)
    .map((edge) => ({ edge, node: nodeById(graph, edge.target) }))
    .filter((item) => item.node)

  return { incoming, outgoing }
}

function edgePriority(kind) {
  const priorities = {
    conclusion: 9,
    requires: 8,
    distinguishes: 8,
    limits: 8,
    rejects: 7,
    causes: 7,
    prepares: 6,
    supports: 5,
    illustrates: 4,
  }
  return priorities[kind] || 1
}

function primaryConnection(items) {
  return [...items].sort(
    (left, right) =>
      edgePriority(right.edge.kind) - edgePriority(left.edge.kind),
  )[0] || null
}

function incomingRole(item) {
  if (!item) return ''
  const title = item.node.title

  switch (item.edge.kind) {
    case 'causes':
      return `Aparece como consecuencia de la dificultad planteada en «${title}».`
    case 'requires':
      return `Se vuelve necesario por lo que exige «${title}».`
    case 'distinguishes':
      return `Se entiende mejor al separarlo de «${title}».`
    case 'rejects':
      return `Entra en escena cuando el argumento deja atrás «${title}».`
    case 'limits':
      return `Hace explícito un límite que ya estaba en juego en «${title}».`
    case 'conclusion':
      return `Recoge una consecuencia obtenida en «${title}».`
    default:
      return ''
  }
}

function outgoingRole(item) {
  if (!item) return ''
  const title = item.node.title

  switch (item.edge.kind) {
    case 'causes':
      return `Su consecuencia inmediata aparece en «${title}».`
    case 'requires':
      return `Obliga a introducir «${title}» para que el argumento pueda continuar.`
    case 'distinguishes':
      return `Abre una distinción que se precisa en «${title}».`
    case 'rejects':
      return `Marca el punto desde el que debe abandonarse «${title}».`
    case 'limits':
      return `Fija la frontera que se desarrolla en «${title}».`
    case 'conclusion':
      return `Permite extraer el resultado formulado en «${title}».`
    default:
      return ''
  }
}

