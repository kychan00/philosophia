export function getKantPrefacesClassNotes(nodeId) {
  const notes = KANT_PREFACES_CLASS_ANNOTATIONS[nodeId] || []

  return notes.map((item) => ({
    ...item,
    source: KANT_PREFACES_CLASS_SOURCE,
  }))
}

export function auditKantPrefacesClassAnnotations(validNodeIds) {
  const valid = new Set(validNodeIds)
  const entries = Object.entries(KANT_PREFACES_CLASS_ANNOTATIONS)
  const orphanNodes = entries
    .map(([nodeId]) => nodeId)
    .filter((nodeId) => !valid.has(nodeId))

  const allNotes = entries.flatMap(([nodeId, notes]) =>
    notes.map((item) => ({ nodeId, ...item })),
  )

  const incompleteNotes = allNotes
    .filter(
      (item) =>
        !item.section ||
        !item.sectionTitle ||
        !item.moment ||
        !item.comment ||
        item.sourceId !== KANT_PREFACES_CLASS_SOURCE.id,
    )
    .map((item) => item.nodeId)

  return {
    annotatedNodes: entries.length,
    notes: allNotes.length,
    orphanNodes,
    incompleteNotes,
  }
}
