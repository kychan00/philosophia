export type MeritTranscriptTurn = {
  speaker: string
  text: string
}

export type MeritTranscriptSection = {
  id: string
  title: string
  turns: MeritTranscriptTurn[]
}

export function parseMeritocracyTranscript(): MeritTranscriptSection[] {
  const rawSections = meritocracyTranscriptRaw
    .split(/\n\s*⸻\s*\n/g)
    .map((section) => section.trim())
    .filter(Boolean)

  return rawSections.map((section, index) => {
    const lines = section.split('\n')
    const title = lines.shift()?.trim() || `Sección ${index + 1}`
    const body = lines.join('\n').trim()
    const parts = body.split(/(?=^Persona \d+:\s*$)/gm).filter(Boolean)

    const turns = parts.map((part) => {
      const match = part.match(/^Persona (\d+):\s*\n?([\s\S]*)$/)
      if (!match) {
        return { speaker: 'Sesión', text: part.trim() }
      }
      return {
        speaker: `Persona ${match[1]}`,
        text: match[2].trim(),
      }
    })

    return {
      id: `section-${String(index + 1).padStart(2, '0')}`,
      title,
      turns,
    }
  })
}
